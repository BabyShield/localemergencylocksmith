// Guard: keep the first entry per slug (matching getAreaBySlug's find()) so an
// accidental duplicate paste can never re-inflate the sitemap, area grids, or
// areaServed schema.
const seenSlugs = new Set<string>()
export const AREAS: Area[] = RAW_AREAS.filter((a) => {
  if (seenSlugs.has(a.slug)) return false
  seenSlugs.add(a.slug)
  return true
})

// One canonical service-area list for structured data. Each entry is a neutral
// Place because the registry includes cities, towns, suburbs, villages and
// neighbourhoods; labelling every entry as a City would be inaccurate.
export const AREA_SERVED_SCHEMA = AREAS.map(area => ({
  '@type': 'Place' as const,
  name: area.name,
}))

export function getAreaBySlug(slug: string): Area | undefined {
  return AREAS.find((a) => a.slug === slug)
}

export function getAreaNeighbours(area: Area): Area[] {
  return area.neighbours
    .map((slug) => AREAS.find((a) => a.slug === slug))
    .filter(Boolean) as Area[]
}

export function getAllAreasByRegion(): Record<string, Area[]> {
  return AREAS.reduce((acc, area) => {
    if (!acc[area.region]) acc[area.region] = []
    acc[area.region].push(area)
    return acc
  }, {} as Record<string, Area[]>)
}
